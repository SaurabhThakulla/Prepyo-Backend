"""Generate PTE Core bank 1 (migration 000108): 10 Write Email + 10 Respond to a Situation.

Formats follow Pearson's PTE Core Score Guide (January 2024) and
https://www.pearsonpte.com/pte-core/test-format/speaking-writing/ . Items are
original and tagged 'PTE Core' in the existing PTE version.
"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from scripts.bank_check import Batch
from scripts.pte_core_b1.email import EMAIL_ITEMS
from scripts.pte_core_b1.rts import RTS_ITEMS

VERSION = 'pte-2026-01'
UP = ROOT / 'migrations' / '000108_pte_core_bank.up.sql'
DOWN = ROOT / 'migrations' / '000108_pte_core_bank.down.sql'
COLUMNS = ('id', 'exam_version_id', 'exam', 'skill', 'type_id', 'type_name', 'title', 'prompt', 'context_passage',
           'audio_transcript', 'model_answer', 'prep_time_seconds', 'time_limit_seconds', 'points', 'difficulty',
           'explanation', 'tags', 'supported_exams', 'is_published')


def words(text):
    return len(text.split())


def email_prompt(item):
    bullets = '\n'.join(f'• {p}' for p in item['points'])
    return (f"Read the situation below. Then write an email in response.\n\n{item['situation']}\n\n"
            f"In your email:\n{bullets}\n\nWrite 50 to 120 words. You have 9 minutes.")


def rows():
    out = []
    for i, item in enumerate(EMAIL_ITEMS, 1):
        out.append({
            'id': f'pte-core-email-{i:03d}', 'skill': 'writing', 'type_id': 'pte-write-email', 'type_name': 'Write Email',
            'title': item['title'], 'prompt': email_prompt(item), 'context_passage': None, 'audio_transcript': None,
            'model_answer': item['model_answer'], 'prep_time_seconds': 0, 'time_limit_seconds': 540,
            'explanation': item['explanation'], 'tag': 'Write Email',
        })
    for i, item in enumerate(RTS_ITEMS, 1):
        out.append({
            'id': f'pte-core-rts-{i:03d}', 'skill': 'speaking', 'type_id': 'pte-respond-to-situation',
            'type_name': 'Respond to a Situation', 'title': item['title'],
            'prompt': item['situation'] + ' In 20 seconds, please prepare your response. You will have 40 seconds to give your response.',
            'context_passage': item['situation'], 'audio_transcript': item['situation'],
            'model_answer': item['model_answer'], 'prep_time_seconds': 20, 'time_limit_seconds': 40,
            'explanation': item['explanation'], 'tag': 'Respond to a Situation',
        })
    for r in out:
        r.update(exam_version_id=VERSION, exam='PTE', points=15, difficulty='medium', supported_exams=['PTE'],
                 is_published=True, tags=['PTE', 'Original practice', 'PTE Core', r.pop('tag')])
    return out


def validate():
    assert len(EMAIL_ITEMS) == 10 and len(RTS_ITEMS) == 10
    batch = Batch()
    for i, item in enumerate(EMAIL_ITEMS, 1):
        where = f'pte-core-email-{i:03d}'
        prompt_words = words(item['situation']) + sum(words(p) for p in item['points'])
        assert prompt_words <= 100, f'{where}: situation and points are {prompt_words} words (Pearson: up to 100)'
        assert len(item['points']) == 3, f'{where}: needs three bullet points'
        model = words(item['model_answer'])
        assert 70 <= model <= 120, f'{where}: model email is {model} words (aim for 70-120)'
        batch.question('PTE', 'pte-write-email', item['title'], item['situation'] + ' ' + ' '.join(item['points']), where=where)
        batch.style(item['model_answer'] + ' ' + item['explanation'], where)
    for i, item in enumerate(RTS_ITEMS, 1):
        where = f'pte-core-rts-{i:03d}'
        assert words(item['situation']) <= 60, f"{where}: situation is {words(item['situation'])} words (Pearson: up to 60)"
        model = words(item['model_answer'])
        assert 50 <= model <= 90, f'{where}: model answer is {model} words (40 seconds of speech is about 50-90)'
        batch.question('PTE', 'pte-respond-to-situation', item['title'], item['situation'], where=where)
        batch.style(item['model_answer'] + ' ' + item['explanation'], where)
    batch.assert_clean()


def lit(value):
    if value is None:
        return 'NULL'
    if isinstance(value, bool):
        return 'TRUE' if value else 'FALSE'
    if isinstance(value, int):
        return str(value)
    if isinstance(value, list):
        return 'ARRAY[' + ', '.join(lit(v) for v in value) + ']::text[]'
    return "'" + value.replace("'", "''") + "'"


def main():
    validate()
    values = ',\n'.join('    (' + ', '.join(lit(r[c]) for c in COLUMNS) + ')' for r in rows())
    sql = ('-- 000108_pte_core_bank.up.sql\n'
           '-- PTE Core bank 1: 10 Write Email and 10 Respond to a Situation, original, tagged PTE Core.\n'
           '-- Generated by scripts/generate_pte_core_b1.py.\n\n'
           f"INSERT INTO questions ({', '.join(COLUMNS)}) VALUES\n{values}\nON CONFLICT (id) DO NOTHING;\n")
    UP.write_text(sql, encoding='utf-8', newline='\n')
    DOWN.write_text('SELECT 1;\n', encoding='utf-8', newline='\n')
    print(f'Wrote {UP.name} with {len(rows())} questions.')


if __name__ == '__main__':
    main()
